const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('dw', {
  screens: (thumbs) => ipcRenderer.invoke('screens', !!thumbs),
  setActiveDisplay: (id) => ipcRenderer.send('active-display', id),
  confirm: (msg) => ipcRenderer.invoke('confirm', msg),
  input: (ev) => ipcRenderer.send('input', ev),
  releaseAll: () => ipcRenderer.send('release-all'),
  clipRead: () => ipcRenderer.invoke('clipboard-read'),
  clipWrite: (t) => ipcRenderer.send('clipboard-write', t),
  fileStart: (m) => ipcRenderer.send('file-start', m),
  fileChunk: (m) => ipcRenderer.send('file-chunk', m),
  fileEnd: (m) => ipcRenderer.send('file-end', m),
  showFile: (p) => ipcRenderer.send('show-file', p),
  onFileSaved: (cb) => ipcRenderer.on('file-saved', (_e, p) => cb(p)),
  systemDark: () => ipcRenderer.invoke('system-dark'),
  onSystemTheme: (cb) => ipcRenderer.on('system-theme', (_e, d) => cb(d)),
  setTheme: (dark) => ipcRenderer.send('theme', dark),
  // unattended access
  authHas: () => ipcRenderer.invoke('auth-has'),
  authSet: (pw) => ipcRenderer.invoke('auth-set', pw),
  authClear: () => ipcRenderer.invoke('auth-clear'),
  authChallenge: (peerId) => ipcRenderer.invoke('auth-challenge', peerId),
  authVerify: (peerId, proof) => ipcRenderer.invoke('auth-verify', peerId, proof),
  authProof: (pw, salt, nonce, iter) => ipcRenderer.invoke('auth-proof', pw, salt, nonce, iter),
  pwRemember: (id, pw) => ipcRenderer.invoke('pw-remember', id, pw),
  pwGet: (id) => ipcRenderer.invoke('pw-get', id),
  pwForget: (id) => ipcRenderer.invoke('pw-forget', id),
  // app / tray
  myId: (id) => ipcRenderer.send('my-id', id),
  mainPrefs: (p) => ipcRenderer.send('main-prefs', p),
  showWindow: () => ipcRenderer.send('show-window'),
  onOpenSettings: (cb) => ipcRenderer.on('open-settings', () => cb()),
  platform: process.platform,
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdateProgress: (cb) => ipcRenderer.on('update-progress', (_e, m) => cb(m)),
  lanStart: (id) => ipcRenderer.invoke('lan-start', id),
  lanInfo: () => ipcRenderer.invoke('lan-info'),
  onLanPeers: (cb) => ipcRenderer.on('lan-peers', (_e, list) => cb(list)),
  adminStatus: () => ipcRenderer.invoke('admin-status'),
  adminRelaunch: () => ipcRenderer.invoke('admin-relaunch'),
  uacNormalDesktop: (on) => ipcRenderer.invoke('uac-normal-desktop', on),
  takePendingLink: () => ipcRenderer.invoke('take-pending-link'),
  onDeepLink: (cb) => ipcRenderer.on('deep-link', (_e, id) => cb(id)),
  appVersion: () => ipcRenderer.invoke('app-version'),
  openExternal: (url) => ipcRenderer.send('open-external', url),
  draw: (m) => ipcRenderer.send('draw', m),
  drawClose: () => ipcRenderer.send('draw-close'),
  macPerms: (prompt) => ipcRenderer.invoke('mac-perms', prompt),
  openMacPref: (which) => ipcRenderer.send('open-mac-pref', which),
  sysinfo: () => ipcRenderer.invoke('sysinfo'),
  lockPc: () => ipcRenderer.send('lock-pc'),
  // media
  recStart: (name) => ipcRenderer.invoke('rec-start', name),
  recChunk: (id, buf) => ipcRenderer.send('rec-chunk', id, buf),
  recEnd: (id) => ipcRenderer.invoke('rec-end', id),
  saveShot: (name, buf) => ipcRenderer.invoke('save-shot', name, buf)
});
